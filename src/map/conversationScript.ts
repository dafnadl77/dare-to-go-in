/** "What came up": the lines of the moments explored, in the order explored, and one way on — in her address. */
export function summaryOf(script: ConversationScript, exploredLabels: readonly string[]): TurnRaw {
  const lines = exploredLabels.map((l) => script.moments.find((m) => m.label === l)).filter((m): m is MomentScript => Boolean(m));
  const unexplored = script.moments.filter((m) => !exploredLabels.includes(m.label));
  const when = script.address === 'masculine' ? 'מתי שתרצה' : script.address === 'feminine' ? 'מתי שתרצי' : 'מתי שירצה הלב';
  const way = unexplored.length ? ` יש עוד רגעים שלא פתחנו, למשל «${unexplored[0].label}». אפשר לחזור אליהם ${when}.` : '';
  return { reply: `${lines.map((m) => m.summary.text).join(' ')}${way}`, offer: '', anchors: [], facts: lines.flatMap((m) => m.summary.facts), move: 'summarize' };
}
