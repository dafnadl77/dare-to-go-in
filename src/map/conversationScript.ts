/**
 * The conversations of the conversation page (conversation.html, development only) and the fixture of tests/conversationTurn*.test.ts.
 * One short conversation for EVERY moment, so any moment can be opened in any order. Each DARE turn is what the model would return
 * (reply, an offer with its anchors, the facts it rests on, its move) and goes through the real checks (checkTurn). Every anchor and
 * fact rests on the dream or on her words in the same moment, so no conversation depends on another one having happened first.
 *
 * Sources: the dreams, the moments and the first answers of the run (acc2-1 / 2 / 3) are real; the conversations approved on paper
 * (docs 101, 102) are kept where they belong to one moment; the rest was written by hand to the principles of doc 102.
 */
import type { TurnRaw, TurnSource } from '../hero/conversationTurn';

export type ScriptTurn = { kind: 'dare'; raw: TurnRaw } | { kind: 'dreamer'; text: string };

export interface MomentScript {
  label: string;
  excerpt: string;
  /** DARE opens; then her words and DARE's, in turn. */
  turns: ScriptTurn[];
  /** This moment's line in "what came up", in the words of the dream and hers. */
  summary: { text: string; facts: TurnSource[] };
}

export interface ConversationScript {
  key: 'store' | 'hall' | 'balcony';
  tab: string;
  runRef: string;
  address: 'masculine' | 'feminine' | 'neutral';
  dreamText: string;
  moments: MomentScript[];
}

const dare = (move: TurnRaw['move'], reply: string, facts: TurnSource[] = [], offer = '', anchors: TurnSource[] = []): ScriptTurn => ({ kind: 'dare', raw: { reply, offer, anchors, facts, move } });
const her = (text: string): ScriptTurn => ({ kind: 'dreamer', text });
const D = (quote: string): TurnSource => ({ quote, from: 'dream' });
const H = (quote: string): TurnSource => ({ quote, from: 'her' });
const line = (text: string, ...facts: TurnSource[]) => ({ text, facts });

